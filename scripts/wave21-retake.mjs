import { chromium } from 'playwright-core';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await chromium.connectOverCDP('http://127.0.0.1:9223', { timeout: 5000 });
const page = browser.contexts()[0].pages().find((p) => p.url().includes('index.html'));
const baseUrl = page.url().split('?')[0];
await page.goto(`${baseUrl}?route=/lab&section=corpus`);
await page.waitForSelector('[data-testid="lab-corpus-intent-ingest"]', { timeout: 90000 });
await sleep(1200);
await page.evaluate(() => {
  const d = document.querySelector('[data-testid="lab-corpus-intent-ingest"]');
  if (d) d.open = true;
});
await sleep(400);
const scope = '[data-testid="lab-corpus-intent-ingest"]';
await page.fill(`${scope} [data-testid="lab-intent-field-lab-intent-document-id"]`, 'doc-smoke-002');
await page.fill(`${scope} [data-testid="lab-intent-field-lab-intent-niche"]`, 'developer-marketing');
await page.fill(`${scope} [data-testid="lab-intent-field-lab-intent-platform"]`, 'mastodon');
await page.fill(`${scope} [data-testid="lab-intent-field-lab-intent-modality"]`, 'text');
await page.fill(`${scope} [data-testid="lab-intent-field-lab-intent-artifact-id"]`, 'artifact-smoke-002');
await page.fill(`${scope} [data-testid="lab-intent-field-lab-intent-source-refs"]`, 'https://example.com/source-a');
await page.fill(`${scope} [data-testid="lab-intent-field-lab-intent-acquired-at"]`, '2026-10-21T12:00:00Z');
await page.fill(`${scope} [data-testid="lab-intent-field-lab-intent-rights-ref"]`, 'rights-smoke-002');
await page.fill(`${scope} [data-testid="lab-intent-field-lab-intent-provenance-ref"]`, 'prov-smoke-002');
await page.click('[data-testid="lab-corpus-intent-ingest-submit"]');
await page.waitForSelector('[data-testid="lab-intent-outcome"]', { timeout: 60000 });
await sleep(600);
const text = await page.textContent('[data-testid="lab-intent-outcome"]');
console.log('OUTCOME:', (text ?? '').slice(0, 240));
await page.screenshot({ path: 'evidence/wave21/packaged-app-lab-ingest-rights-rejection.png', fullPage: true });
console.log('retaken');
await browser.close();
